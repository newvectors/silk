// Package silkgen shares source generation between the IDE and command-line
// generator. It does not import GUI factories or initialize native windows.
package silkgen

import (
	"fmt"
	"go/format"
	"go/token"
	"path/filepath"
	"strings"
	"unicode"

	"github.com/uk0/silk/decl"
)

// GenerateSource produces the complete, formatted Go file for a widget tree.
// An empty functionName derives a safe Build-prefixed name from input.
func GenerateSource(input, packageName, functionName string, tree *decl.Node) ([]byte, error) {
	if !token.IsIdentifier(packageName) || packageName == "_" {
		return nil, fmt.Errorf("invalid package name %q", packageName)
	}
	if functionName == "" {
		functionName = DefaultBuildName(input)
	}
	if !token.IsIdentifier(functionName) || functionName == "_" || functionName == "init" || functionName == "decl" || (packageName == "main" && functionName == "main") {
		return nil, fmt.Errorf("invalid build function name %q", functionName)
	}
	if tree == nil {
		return nil, fmt.Errorf("nil widget tree")
	}
	// Quote filenames in comments: filenames can contain newlines on Unix,
	// but must never introduce source lines or break a generated Go program.
	source := fmt.Sprintf(`// Code generated by silkgen — DO NOT EDIT.
// Source: %q

package %s

import "github.com/uk0/silk/decl"

// %s constructs the widget tree. Import the relevant factory package
// (normally gui) in the application, then call (*decl.Node).Build().
func %s() *decl.Node {
 return %s
}
`, filepath.Base(input), packageName, functionName, functionName, decl.ToGo(tree))
	return format.Source([]byte(source))
}

// DefaultBuildName keeps already-valid stems stable, treating punctuation and
// spaces as word boundaries. Unicode letters and digits remain intact.
func DefaultBuildName(input string) string {
	base := filepath.Base(input)
	stem := strings.TrimSuffix(base, filepath.Ext(base))
	var name strings.Builder
	name.WriteString("Build")
	upper := true
	for _, r := range stem {
		if unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_' {
			if upper {
				r = unicode.ToUpper(r)
			}
			name.WriteRune(r)
			upper = false
		} else {
			upper = true
		}
	}
	if name.Len() == len("Build") {
		name.WriteString("Form")
	}
	return name.String()
}
